// A managed Minecraft server: files on disk + the running Java process.

import { spawn, type ChildProcess } from "node:child_process";
import { createHash } from "node:crypto";
import { EventEmitter } from "node:events";
import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { pickJava } from "./java.ts";
import { preset, teamCommands, writeLifesteal } from "./presets.ts";
import { download, exists, resolve } from "./versions.ts";

export interface InstanceSpec {
  id: string;
  name: string;
  software: "vanilla" | "paper" | "custom";
  version: string;
  port: number;
  auth_mode: "online" | "offline";
  gamemode: string;
  difficulty: string;
  seed: string;
  world_type: string;
  max_players: number;
  memory_mb: number;
  custom_command: string;
  whitelist: string[];
  ops: string[];
  smp_preset: string | null;
  teams?: { name: string; color?: string; members: string[] }[];
  properties: Record<string, string>;
  eula_accepted_at: number | null;
  bind_ip?: string;
}

export type InstanceState = "stopped" | "installing" | "starting" | "running" | "stopping" | "crashed";

export function offlineUuid(name: string): string {
  const h = createHash("md5").update("OfflinePlayer:" + name).digest();
  h[6] = (h[6] & 0x0f) | 0x30;
  h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.toString("hex");
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}

const LEVEL_TYPES: Record<string, string> = {
  default: "minecraft\\:normal",
  flat: "minecraft\\:flat",
  large_biomes: "minecraft\\:large_biomes",
  amplified: "minecraft\\:amplified",
};

export function buildProperties(s: InstanceSpec): Record<string, string> {
  const hardcore = s.gamemode === "hardcore";
  const p: Record<string, string> = {
    "server-port": String(s.port),
    "query.port": String(s.port),
    motd: `${s.name} (OmniPlayer)`,
    "online-mode": s.auth_mode === "online" ? "true" : "false",
    gamemode: hardcore ? "survival" : s.gamemode,
    hardcore: hardcore ? "true" : "false",
    difficulty: hardcore ? "hard" : s.difficulty,
    "level-seed": s.seed ?? "",
    "level-type": LEVEL_TYPES[s.world_type] ?? LEVEL_TYPES.default,
    "max-players": String(s.max_players),
    "view-distance": "10",
    "simulation-distance": "10",
    "enable-command-block": "false",
    "spawn-protection": "0",
    // RCON is never enabled: the manager drives the console through stdin.
    "enable-rcon": "false",
    "enable-query": "false",
  };
  if (s.bind_ip) p["server-ip"] = s.bind_ip;
  if (s.auth_mode === "offline") {
    // Private offline server: only allow-listed names may join.
    p["white-list"] = "true";
    p["enforce-whitelist"] = "true";
    p["enforce-secure-profile"] = "false";
  } else {
    p["white-list"] = s.whitelist.length ? "true" : "false";
    // Bots on online servers cannot sign chat yet (see docs/ACCOUNTS.md).
    p["enforce-secure-profile"] = "false";
  }
  const pr = s.smp_preset ? preset(s.smp_preset) : undefined;
  if (pr) Object.assign(p, pr.properties);
  Object.assign(p, s.properties ?? {});
  return p;
}

export function serializeProperties(p: Record<string, string>): string {
  const lines = ["#Minecraft server properties", "#Generated by OmniPlayer (edit through the dashboard)"];
  for (const [k, v] of Object.entries(p)) lines.push(`${k}=${v}`);
  return lines.join("\n") + "\n";
}

export function parseProperties(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    if (!line || line.startsWith("#")) continue;
    const i = line.indexOf("=");
    if (i > 0) out[line.slice(0, i)] = line.slice(i + 1);
  }
  return out;
}

export interface Metrics {
  pid: number | null;
  cpu_percent: number;
  rss_mb: number;
  uptime_s: number;
}

export class ServerInstance extends EventEmitter {
  spec: InstanceSpec;
  dir: string;
  state: InstanceState = "stopped";
  proc: ChildProcess | null = null;
  console: string[] = [];
  players = new Set<string>();
  startedAt = 0;
  lastError = "";
  private cpuSample: { t: number; ticks: number } | null = null;
  private firstStart = false;

  constructor(spec: InstanceSpec, rootDir: string) {
    super();
    this.spec = spec;
    this.dir = join(rootDir, spec.id);
  }

  private log(line: string) {
    this.console.push(line);
    if (this.console.length > 2000) this.console.splice(0, this.console.length - 2000);
    this.emit("console", line);
    // Vanilla/Paper log patterns.
    let m = line.match(/: (\w{3,16}) joined the game/);
    if (m) {
      this.players.add(m[1]);
      this.emit("player", { event: "join", name: m[1] });
    }
    m = line.match(/: (\w{3,16}) left the game/);
    if (m) {
      this.players.delete(m[1]);
      this.emit("player", { event: "leave", name: m[1] });
    }
    if (/\bDone \([\d.]+s\)!/.test(line) && this.state === "starting") {
      this.setState("running");
      this.onReady();
    }
  }

  private setState(s: InstanceState) {
    this.state = s;
    this.emit("state", s);
  }

  get jarPath() {
    return join(this.dir, "server.jar");
  }

  /** Writes config files. The EULA file is only written after explicit acceptance. */
  async writeConfig(): Promise<void> {
    await mkdir(this.dir, { recursive: true });
    const propsFile = join(this.dir, "server.properties");
    let existing: Record<string, string> = {};
    if (await exists(propsFile)) existing = parseProperties(await readFile(propsFile, "utf8"));
    const props = { ...existing, ...buildProperties(this.spec) };
    await writeFile(propsFile, serializeProperties(props));
    const wl = this.spec.whitelist.map((name) => ({ uuid: offlineUuidIfOffline(this.spec, name), name }));
    if (this.spec.auth_mode === "offline") await writeFile(join(this.dir, "whitelist.json"), JSON.stringify(wl, null, 2));
    if (this.spec.auth_mode === "offline" && this.spec.ops.length) {
      const ops = this.spec.ops.map((name) => ({ uuid: offlineUuid(name), name, level: 4, bypassesPlayerLimit: false }));
      await writeFile(join(this.dir, "ops.json"), JSON.stringify(ops, null, 2));
    }
    if (this.spec.eula_accepted_at) {
      await writeFile(
        join(this.dir, "eula.txt"),
        `#By changing the setting below to TRUE you are indicating your agreement to the Minecraft EULA (https://aka.ms/MinecraftEULA).\n#Accepted in the OmniPlayer dashboard at ${new Date(this.spec.eula_accepted_at).toISOString()}\neula=true\n`,
      );
    }
    const pr = this.spec.smp_preset ? preset(this.spec.smp_preset) : undefined;
    if (pr?.datapack === "lifesteal") await writeLifesteal(join(this.dir, "world"));
  }

  async install(onProgress?: (msg: string) => void): Promise<void> {
    if (this.spec.software === "custom") return;
    if (await exists(this.jarPath)) return;
    this.setState("installing");
    try {
      onProgress?.(`Resolving ${this.spec.software} ${this.spec.version}`);
      const jar = await resolve(this.spec.software, this.spec.version);
      await writeFile(join(this.dir, "omniplayer-jar.json"), JSON.stringify(jar, null, 2));
      onProgress?.(`Downloading ${jar.url}`);
      await download(jar, this.jarPath, (p) => onProgress?.(`Downloading ${p}%`));
      onProgress?.("Downloaded and checksum verified");
      this.setState("stopped");
    } catch (e) {
      this.setState("stopped");
      throw e;
    }
  }

  async start(): Promise<void> {
    if (this.proc) throw new Error("server is already running");
    if (this.spec.software !== "custom" && !this.spec.eula_accepted_at) {
      throw new Error("The Minecraft EULA must be accepted in the dashboard before this server can start.");
    }
    await this.writeConfig();
    this.firstStart = !(await exists(join(this.dir, "world", "level.dat")));
    let cmd: string;
    let args: string[];
    if (this.spec.software === "custom") {
      const parts = this.spec.custom_command.split(" ").filter(Boolean);
      if (!parts.length) throw new Error("custom server needs a start command");
      cmd = parts[0];
      args = parts.slice(1).map((a) => a.replace("{port}", String(this.spec.port)));
    } else {
      await this.install((m) => this.log(`[omniplayer] ${m}`));
      let javaMajor = 21;
      try {
        javaMajor = JSON.parse(await readFile(join(this.dir, "omniplayer-jar.json"), "utf8")).javaMajor ?? 21;
      } catch {
        /* default */
      }
      const java = await pickJava(javaMajor);
      cmd = java.path;
      args = [`-Xms${Math.min(1024, this.spec.memory_mb)}M`, `-Xmx${this.spec.memory_mb}M`, "-jar", "server.jar", "nogui"];
      this.log(`[omniplayer] using Java ${java.version} at ${java.path}`);
    }
    this.setState("starting");
    this.startedAt = Date.now();
    this.cpuSample = null;
    const proc = spawn(cmd, args, { cwd: this.dir, stdio: ["pipe", "pipe", "pipe"], env: { ...process.env, JAVA_TOOL_OPTIONS: "" } });
    this.proc = proc;
    let buf = "";
    const onData = (d: Buffer) => {
      buf += d.toString();
      let i;
      while ((i = buf.indexOf("\n")) >= 0) {
        this.log(buf.slice(0, i).replace(/\r$/, ""));
        buf = buf.slice(i + 1);
      }
    };
    proc.stdout!.on("data", onData);
    proc.stderr!.on("data", onData);
    proc.on("exit", (code, sig) => {
      this.proc = null;
      this.players.clear();
      const expected = this.state === "stopping";
      this.log(`[omniplayer] server process exited (code ${code}${sig ? ", signal " + sig : ""})`);
      if (!expected && code !== 0) this.lastError = `exited with code ${code}`;
      this.setState(expected || code === 0 ? "stopped" : "crashed");
    });
    // Custom servers (e.g. the integration test server) may not print "Done (".
    if (this.spec.software === "custom") {
      const t = setInterval(() => {
        if (this.state !== "starting") return clearInterval(t);
        if (this.console.some((l) => /READY|Done \(/.test(l))) {
          clearInterval(t);
          this.setState("running");
          this.onReady();
        }
      }, 250);
    }
  }

  private onReady() {
    const pr = this.spec.smp_preset ? preset(this.spec.smp_preset) : undefined;
    if (this.firstStart) {
      for (const c of pr?.first_start_commands ?? []) this.command(c);
      if (this.spec.teams?.length) for (const c of teamCommands(this.spec.teams)) this.command(c);
    }
    if (this.spec.auth_mode === "offline") this.command("whitelist reload");
  }

  command(line: string): void {
    if (!this.proc?.stdin?.writable) throw new Error("server is not running");
    this.proc.stdin.write(line.replace(/[\r\n]/g, " ") + "\n");
    this.log(`> ${line}`);
  }

  async stop(timeoutMs = 60_000): Promise<void> {
    const p = this.proc;
    if (!p) return;
    this.setState("stopping");
    try {
      this.command("stop");
    } catch {
      p.kill("SIGTERM");
    }
    await new Promise<void>((resolve) => {
      const t = setTimeout(() => {
        p.kill("SIGKILL");
        resolve();
      }, timeoutMs);
      p.once("exit", () => {
        clearTimeout(t);
        resolve();
      });
    });
  }

  async restart(): Promise<void> {
    await this.stop();
    await this.start();
  }

  async whitelistAdd(name: string): Promise<void> {
    if (!this.spec.whitelist.includes(name)) this.spec.whitelist.push(name);
    await this.writeConfig();
    if (this.proc) this.command("whitelist reload");
  }

  async whitelistRemove(name: string): Promise<void> {
    this.spec.whitelist = this.spec.whitelist.filter((n) => n !== name);
    await this.writeConfig();
    if (this.proc) {
      this.command("whitelist reload");
      this.command(`kick ${name} Removed from the allowlist`);
    }
  }

  /** Real CPU% and resident memory from /proc (Linux). */
  async metrics(): Promise<Metrics> {
    const pid = this.proc?.pid ?? null;
    if (!pid) return { pid: null, cpu_percent: 0, rss_mb: 0, uptime_s: 0 };
    try {
      const stat = (await readFile(`/proc/${pid}/stat`, "utf8")).split(") ")[1].split(" ");
      const ticks = Number(stat[11]) + Number(stat[12]);
      const now = Date.now();
      let cpu = 0;
      if (this.cpuSample) cpu = ((ticks - this.cpuSample.ticks) / 100 / ((now - this.cpuSample.t) / 1000)) * 100;
      this.cpuSample = { t: now, ticks };
      const status = await readFile(`/proc/${pid}/status`, "utf8");
      const rss = Number(status.match(/VmRSS:\s+(\d+)/)?.[1] ?? 0) / 1024;
      return { pid, cpu_percent: Math.round(cpu * 10) / 10, rss_mb: Math.round(rss), uptime_s: Math.round((now - this.startedAt) / 1000) };
    } catch {
      return { pid, cpu_percent: 0, rss_mb: 0, uptime_s: Math.round((Date.now() - this.startedAt) / 1000) };
    }
  }

  /** World backup (tar.gz). Saving is paused during the copy when running. */
  async backup(backupDir: string): Promise<string> {
    await mkdir(backupDir, { recursive: true });
    const file = join(backupDir, `${this.spec.id}-${new Date().toISOString().replace(/[:.]/g, "-")}.tar.gz`);
    const running = !!this.proc;
    if (running) {
      this.command("save-off");
      this.command("save-all flush");
      await new Promise((r) => setTimeout(r, 3000));
    }
    try {
      const worlds = (await readdir(this.dir)).filter((d) => d.startsWith("world"));
      if (!worlds.length) throw new Error("no world folder yet (start the server once)");
      await new Promise<void>((resolve, reject) => {
        const t = spawn("tar", ["-czf", file, ...worlds], { cwd: this.dir });
        t.on("exit", (c) => (c === 0 ? resolve() : reject(new Error(`tar exited with ${c}`))));
        t.on("error", reject);
      });
    } finally {
      if (running) this.command("save-on");
    }
    return file;
  }

  async listBackups(backupDir: string): Promise<{ file: string; size: number; created: number }[]> {
    try {
      const files = (await readdir(backupDir)).filter((f) => f.startsWith(this.spec.id + "-") && f.endsWith(".tar.gz"));
      const out = [];
      for (const f of files) {
        const s = await stat(join(backupDir, f));
        out.push({ file: f, size: s.size, created: s.mtimeMs });
      }
      return out.sort((a, b) => b.created - a.created);
    } catch {
      return [];
    }
  }
}

function offlineUuidIfOffline(spec: InstanceSpec, name: string): string {
  return spec.auth_mode === "offline" ? offlineUuid(name) : "";
}
