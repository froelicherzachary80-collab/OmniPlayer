/// All adapters compiled into this build, newest first.
pub fn supported() -> Vec<VersionAdapter> {
    vec![adapter_26_3()]
}

pub fn by_name(name: &str) -> Option<VersionAdapter> {
    supported().into_iter().find(|a| a.name == name)
}

pub fn by_protocol(p: i32) -> Option<VersionAdapter> {
    supported().into_iter().find(|a| a.protocol == p)
}
